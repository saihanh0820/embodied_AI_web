const ATTRIBUTES = ["aria-label", "placeholder", "alt", "title", "data-news-title"];
let dynamicContentObserver;

function translateValue(value) {
  if (Object.prototype.hasOwnProperty.call(EN, value)) return EN[value];

  const requiredField = value.match(/^\*(.+)$/);
  if (requiredField && Object.prototype.hasOwnProperty.call(EN, requiredField[1])) {
    return `*${EN[requiredField[1]]}`;
  }

  const year = value.match(/^(\d{4})年$/);
  if (year) return year[1];

  const page = value.match(/^第(\d+)页$/);
  if (page) return `Page ${page[1]}`;

  const certificate = value.match(/^微眸医疗发明专利证书\s*(\d+)$/);
  if (certificate) return `Oculotronics invention patent certificate ${certificate[1]}`;

  return value
    .replace("电话：", "Tel: ")
    .replace("邮箱：", "Email: ")
    .replace("地址：", "Address: ")
    .replace("销售专线", "Sales")
    .replace("广州市南沙区珠江街南江二路6号自编8栋(9#楼)8层803", "Room 803, Building 8 (Building 9), No. 6 Nanjiang 2nd Road, Zhujiang Street, Nansha District, Guangzhou")
    .replace("广州市越秀区先烈中路65号东山广场附楼10楼", "10/F, Annex Building, No. 65 Xianlie South Road, Dongshan Plaza, Yuexiu District, Guangzhou")
    .replaceAll("（", "(")
    .replaceAll("）", ")");
}

export function readLocale() {
  try {
    return localStorage.getItem("oculotronics-locale") === "en" ? "en" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

export function applyLocale(locale, root = document.body) {
  const english = locale === "en";
  document.documentElement.lang = english ? "en" : "zh-CN";
  document.body.dataset.locale = english ? "en" : "zh";
  if (!english) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const original = node.nodeValue;
    const value = original.trim();
    if (value && Object.prototype.hasOwnProperty.call(EN, value)) {
      const leading = original.match(/^\s*/)?.[0] || "";
      const trailing = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = `${leading}${EN[value]}${trailing}`;
    } else if (value) {
      const leading = original.match(/^\s*/)?.[0] || "";
      const trailing = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = `${leading}${translateValue(value)}${trailing}`;
    }
    node = walker.nextNode();
  }

  root.querySelectorAll("*").forEach((element) => {
    ATTRIBUTES.forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translateValue(value));
    });
  });

  if (!dynamicContentObserver && document.body) {
    dynamicContentObserver = new MutationObserver((mutations) => {
      if (document.documentElement.lang !== "en") return;
      mutations.forEach((mutation) => {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.ELEMENT_NODE) applyLocale("en", node);
          else if (node.nodeType === Node.TEXT_NODE && node.parentElement) applyLocale("en", node.parentElement);
        });
      });
    });
    dynamicContentObserver.observe(document.body, { childList: true, subtree: true });
  }
}

export function localeText(zh, en) {
  return document.documentElement.lang === "en" ? en : zh;
}

export function translateText(value) {
  return document.documentElement.lang === "en" ? translateValue(value) : value;
}
