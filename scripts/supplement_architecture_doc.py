def add_underlined(text, style=None, size=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.underline = True
    if style:
        run.bold = True
        run.font.size = Pt(14 if "1" in style else 12)
    if size:
        run.font.size = Pt(size)
    return p

